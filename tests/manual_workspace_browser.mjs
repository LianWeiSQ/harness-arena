// Start tests/manual_workspace_server.py first. This operates only its controlled data.
const {chromium}=await import(process.env.EVO_PLAYWRIGHT_MODULE||'playwright');
import fs from 'node:fs/promises';
import assert from 'node:assert/strict';
await fs.mkdir('.evoarena',{recursive:true});
const browser=await chromium.launch({headless:true});
const page=await browser.newPage({viewport:{width:1440,height:1000}});
const errors=[];page.on('pageerror',e=>errors.push(e.message));page.on('response',async r=>{if(r.request().method()==='POST'&&r.status()>=400)console.log('API ERROR',r.status(),await r.text());});
const base='http://127.0.0.1:8795';
const overview=()=>fetch(base+'/api/evo').then(r=>r.json());
try{
 await page.goto(base+'/evo');
 await page.locator('#new-project').click();
 await page.locator('#project-name').fill('工程验证 · 订单助手');
 await page.locator('#project-goal').fill('核对下单结果，避免重复创建订单。此工作区使用受控测试数据，不代表真实模型收益。');
 await page.locator('#project-target').selectOption('policy.md');
 await page.locator('#project-submit').click();
 await page.locator('#workspace-summary').getByText(/核对下单结果/).waitFor();
 const project=(await overview()).projects[0].id;
 await page.locator('#open-experiment').click();
 await page.locator('#improve-stage').selectOption('diagnose');
 await page.locator('#run-experiment').click();
 await page.locator('[data-next-stage="propose"]').waitFor({timeout:20000});
 assert.equal((await overview()).projects[0].cost.calls,7);
 assert.match(await page.locator('#experiment-body').innerText(),/诊断已保存/);
 assert.equal(await page.locator('.evo-coverage').count(),0);
 console.log('diagnosis: 7 calls, stage complete, no validation scoreboard');
 await page.locator('[data-next-stage="propose"]').click();
 await page.locator('#run-experiment').click();
 await page.locator('[data-next-stage="validate"]').waitFor({timeout:20000});
 assert.equal((await overview()).projects[0].cost.calls,8);
 await page.locator('[data-scroll="reasoning"]').click();
 assert.equal(new URL(page.url()).hash,'#experiments');
 console.log('proposal: 1 additional call, source navigation stays in experiments');
 await page.locator('[data-next-stage="validate"]').click();
 await page.locator('#run-experiment').click();
 await page.locator('.evo-result-head strong').filter({hasText:'接受候选'}).waitFor({timeout:20000});
 let data=await overview();assert.equal(data.projects[0].cost.calls,32);assert.equal(data.projects[0].revision,1);
 const validated=data.experiments[0].id;
 console.log('validation: 24 additional calls, recommendation updated in original project');
 await page.locator('#new-campaign').click();await page.locator('#campaign-submit').click();
 await page.locator('#campaign-list b').filter({hasText:'计划完成'}).waitFor({timeout:25000});
 data=await overview();assert.equal(data.campaigns[0].budget.calls,96);assert.equal(data.projects[0].cost.calls,128);assert.equal(data.projects[0].revision,4);
 console.log('campaign: 3 generations, 96 calls, project total 128');
 await page.locator('#new-campaign').click();await page.locator('#campaign-submit').click();
 await page.locator('[data-cancel-campaign]').click();
 await page.locator('#campaign-list b').filter({hasText:'已取消'}).waitFor({timeout:20000});
 data=await overview();assert.equal(data.projects[0].revision,4);
 console.log('cancel: no later adoption, active work stopped');
 await page.locator('#history').selectOption(validated);
 await page.locator('.evo-result-head strong').filter({hasText:'接受候选'}).waitFor();
 await page.evaluate(()=>window.scrollTo(0,0));
 await page.screenshot({path:'.evoarena/workspace-desktop.png',fullPage:true});
 await page.setViewportSize({width:390,height:844});
 await page.screenshot({path:'.evoarena/workspace-mobile.png',fullPage:true});
 const overflow=await page.evaluate(()=>({viewport:innerWidth,width:document.documentElement.scrollWidth}));
 assert.ok(overflow.width<=overflow.viewport,JSON.stringify(overflow));
 await page.setViewportSize({width:1440,height:1000});
 const download=page.waitForEvent('download');await page.locator('#export-project').click();await (await download).saveAs('.evoarena/workspace-export.zip');
 await page.locator('#new-project').click();await page.locator('#project-name').fill('工程验证 · 空项目');await page.locator('#project-goal').fill('检查空工作区不会显示其他项目结果');await page.locator('#project-submit').click();
 await page.locator('#experiment-body').getByText('本项目还没有实验，可从分析执行反馈开始。').waitFor();
 assert.equal(await page.locator('#comparison-summary').innerText(),'');
 await page.locator('#workspace').selectOption(project);
 await page.locator('#comparison-summary .evo-journey').waitFor();
 assert.deepEqual(errors,[]);
 await fs.writeFile('.evoarena/workspace-ui-result.json',JSON.stringify({passed:true,controlled_only:true,model_network_calls:0,overflow,errors,project,validated},null,2));
 console.log('desktop/mobile, download, empty workspace, project switching: passed');
}finally{await browser.close();}
